int	ft_strcmp(char *s1, char *s2)
{
	long int	i;
	long int	s1v;
	long int	s2v;

	s1v = 0;
	s2v = 0;
	while (s1[i])
	{
		s1v += s1[i];
		i++;
	}
	i = 0;
	while (s2[i])
	{
		s2v += s2[i];
		i++;
	}
	return (s1v - s2v);
}


