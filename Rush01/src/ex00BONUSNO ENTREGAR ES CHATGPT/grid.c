#include "rush.h"

void	init_tab(int tab[9][9])
{
	int	i;
	int	j;

	i = 0;
	j = 0;
	while (i < 9)
	{
		while (j < 9)
		{
			tab[i][j] = 0;
			j++;
		}
		j = 0;
		i++;
	}
}
